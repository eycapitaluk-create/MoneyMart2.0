/**
 * Fund Name Convention xlsx → stock_symbols 用 UPDATE SQL（手動実行用）
 *
 *   node scripts/generate-fund-convention-sql-patch.mjs [path/to.xlsx] [--out=reports/patch.sql]
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import XLSX from 'xlsx'
import { normalizeFundDisplayNamePlain, normalizeNisaCategoryField } from '../src/lib/textEncodingUtils.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')

const sqlLiteral = (s) => `'${String(s).replace(/'/g, "''")}'`

const defaultXlsx = '/Users/justinnam/Downloads/Fund Name Convention.xlsx'
const cliArgs = process.argv.slice(2).filter((a) => !a.startsWith('--'))
const xlsxPath = path.resolve(cliArgs[0] || defaultXlsx)
const outArg = process.argv.find((a) => a.startsWith('--out='))
const outPath = outArg
  ? path.resolve(outArg.slice('--out='.length))
  : path.join(root, 'reports', `SUPABASE_PATCH_fund_convention_${new Date().toISOString().slice(0, 10)}.sql`)

const wb = XLSX.readFile(xlsxPath)
const ws = wb.Sheets.fund_list || wb.Sheets[wb.SheetNames[0]]
const matrix = XLSX.utils.sheet_to_json(ws, { header: 1, defval: '' })
const header = matrix[0] || []
const idx = (label) => header.findIndex((h) => String(h || '').trim() === label)
const iSym = idx('銘柄')
const iIsin = idx('ISIN')
const iJp = idx('ファンド名JP')
const iOff = idx('Official Name')
const iNisa = idx('NISA区分')
if (iSym < 0) throw new Error('銘柄 column required')

const nisaForce = new Set(['1540.T', '1541.T', '1542.T', '1543.T'])

const lines = [
  '-- Generated by scripts/generate-fund-convention-sql-patch.mjs',
  '-- Run in Supabase SQL editor (stock_symbols must exist)',
  'BEGIN;',
]

for (let r = 1; r < matrix.length; r += 1) {
  const row = matrix[r]
  if (!row?.length) continue
  const symbol = String(row[iSym] || '').trim().toUpperCase()
  if (!symbol) continue
  const official = iOff >= 0 ? String(row[iOff] || '').trim() : ''
  const nameJp = iJp >= 0 ? String(row[iJp] || '').trim() : ''
  const displayRaw = (official || nameJp).trim()
  const name = normalizeFundDisplayNamePlain(displayRaw) || displayRaw || symbol
  let nisa = ''
  if (iNisa >= 0) nisa = normalizeNisaCategoryField(String(row[iNisa] || '').trim() || '-')
  if (nisaForce.has(symbol)) nisa = normalizeNisaCategoryField('成長')
  if (nisa === '-') nisa = ''
  const parts = [`name = ${sqlLiteral(name)}`]
  if (nisa) parts.push(`nisa_category = ${sqlLiteral(nisa)}`)
  lines.push(`UPDATE stock_symbols SET ${parts.join(', ')} WHERE symbol = ${sqlLiteral(symbol)};`)
}

lines.push('COMMIT;')

fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8')
console.log(`Wrote ${outPath} (${lines.length - 3} updates)`)
