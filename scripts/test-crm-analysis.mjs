import assert from 'node:assert/strict'
import { build } from 'esbuild'
const bundle = await build({entryPoints:['src/lib/crmAdvancedAnalysis.js'],bundle:true,write:false,format:'esm',platform:'node'})
const {buildCrmAdvancedAnalysis:analyze,buildCrmDecisionMetrics:metrics,wilsonInterval} = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`)
const now=Date.parse('2026-10-22T08:00:00Z'), day=86400000
const row=(age, activated=false, intent=false)=>({user_created_at:new Date(now-age*day).toISOString(),is_internal:false,is_activated:activated,has_premium_intent:intent,signup_utm_source:'x'})
const run=(allRows,extra={})=>analyze({allRows,now,sessions:100,...extra})
const current=Array.from({length:8},(_,i)=>row(10,i<6))
const prior=Array.from({length:8},(_,i)=>row(40,i<4))
const comparison=run([...current,...prior])
assert.equal(comparison.pop.activationPct.deltaPp,25)
assert.equal(comparison.pop.signups.deltaPct,0)
assert.equal(comparison.pop.activationPct.deltaPct,undefined)
const pending=run(Array.from({length:10},()=>row(1)))
assert.equal(pending.current.matured.n,0)
assert.equal(pending.current.pending,10)
assert.equal(pending.current.matured.activationPct,null)
assert.equal(pending.channelQuality[0].quality,null)
assert.equal(pending.constraint,'observation')
const failed=run([],{dataStatus:{customers:'error',traffic:'error'}})
assert.equal(metrics(failed).signups,null)
assert.equal(metrics(failed).sessions,null)
assert.equal(failed.constraint,'measurement')
assert.equal(metrics(run([],{sessions:0})).signups,0)
assert.equal(metrics(run([],{sessions:0})).visitToSignupPct,null)
const capped=run(Array.from({length:300},()=>row(1)))
assert.equal(capped.coverage.currentComplete,false)
assert.equal(capped.pop.signups.deltaPct,null)
assert.equal(metrics(capped).visitToSignupPct,null)
const staffCapped=run(Array.from({length:300},()=>({...row(1),is_internal:true})))
assert.equal(staffCapped.current.n,0)
assert.equal(staffCapped.coverage.currentComplete,false)
const covered=run([...Array.from({length:299},()=>row(10)),row(80)])
assert.equal(covered.coverage.previousComplete,true)
const independent=metrics(run([row(10,false,true)]))
assert.equal(independent.signupToIntentPct,100)
assert.equal(independent.activationToIntentPct,null)
const invalid=run([{user_created_at:'bad'},row(-1)])
assert.equal(invalid.coverage.invalidDates,2)
assert.equal(invalid.constraint,'measurement')
assert.equal(wilsonInterval(NaN,8),null)
assert.equal(wilsonInterval(9,8),null)
assert.ok(wilsonInterval(4,8).lowPct<50)
console.log('CRM regression checks passed: pp, pending cohorts, failed vs zero, bounded coverage, staff exclusion, intent denominator, invalid dates, confidence interval.')
